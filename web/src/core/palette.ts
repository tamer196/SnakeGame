/**
 * Colour system for NEON SERPENT - a port of `snake/palette.py`.
 *
 * Every level owns a {@link Theme}: a small, coherent set of colours plus the
 * name of the background style that should be drawn behind it. Renderers never
 * invent colours - they pull them from the active theme so the whole frame
 * reads as one designed image instead of a pile of unrelated hues.
 *
 * Colours are plain RGB triples of ints 0..255, exactly as in Python. Because
 * Pixi wants packed `0xRRGGBB` numbers, every theme also carries a `hex` mirror
 * of its palette, converted **once at module load** rather than per frame.
 *
 * The twelve themes are loaded from `data/themes.json` (generated by
 * `tools/export_data.py`); nothing is retyped here.
 */

import rawThemes from "../data/themes.json";

/** An RGB colour, channels 0..255. */
export type RGB = readonly [number, number, number];

/** An RGBA colour, channels 0..255. */
export type RGBA = readonly [number, number, number, number];

// ---------------------------------------------------------------------------
// Colour maths (ported 1:1 from palette.py)
// ---------------------------------------------------------------------------

/** Clamp a number into a valid 0..255 channel value (truncating, like Python). */
export function clamp8(v: number): number {
  if (!Number.isFinite(v)) return 0;
  return v < 0 ? 0 : v > 255 ? 255 : Math.trunc(v);
}

/** Linear blend between two colours; `t` is clamped to 0..1. */
export function lerpColor(a: RGB, b: RGB, t: number): RGB {
  const k = t < 0 ? 0 : t > 1 ? 1 : t;
  return [
    clamp8(a[0] + (b[0] - a[0]) * k),
    clamp8(a[1] + (b[1] - a[1]) * k),
    clamp8(a[2] + (b[2] - a[2]) * k),
  ];
}

/** Multiply brightness. `factor` < 1 darkens, > 1 lightens (saturating). */
export function shade(c: RGB, factor: number): RGB {
  return [clamp8(c[0] * factor), clamp8(c[1] * factor), clamp8(c[2] * factor)];
}

/** Attach an alpha channel (0..255) to an RGB colour. */
export function withAlpha(c: RGB, a: number): RGBA {
  return [Math.trunc(c[0]), Math.trunc(c[1]), Math.trunc(c[2]), clamp8(a)];
}

/** Port of `colorsys.hsv_to_rgb`; h wraps, s and v are clamped to 0..1. */
function hsvToRgbFloat(h: number, s: number, v: number): [number, number, number] {
  if (s <= 0) return [v, v, v];
  const i = Math.floor(h * 6.0);
  const f = h * 6.0 - i;
  const p = v * (1.0 - s);
  const q = v * (1.0 - s * f);
  const t = v * (1.0 - s * (1.0 - f));
  switch (((i % 6) + 6) % 6) {
    case 0:
      return [v, t, p];
    case 1:
      return [q, v, p];
    case 2:
      return [p, v, t];
    case 3:
      return [p, q, v];
    case 4:
      return [t, p, v];
    default:
      return [v, p, q];
  }
}

/** Port of `colorsys.rgb_to_hsv`; inputs and outputs are floats in 0..1. */
function rgbToHsvFloat(r: number, g: number, b: number): [number, number, number] {
  const maxc = Math.max(r, g, b);
  const minc = Math.min(r, g, b);
  const rangec = maxc - minc;
  const v = maxc;
  if (minc === maxc) return [0.0, 0.0, v];
  const s = rangec / maxc;
  const rc = (maxc - r) / rangec;
  const gc = (maxc - g) / rangec;
  const bc = (maxc - b) / rangec;
  let h: number;
  if (r === maxc) h = bc - gc;
  else if (g === maxc) h = 2.0 + rc - bc;
  else h = 4.0 + gc - rc;
  h = (h / 6.0) % 1.0;
  if (h < 0) h += 1.0;
  return [h, s, v];
}

/** Build an RGB colour from HSV floats in 0..1 (h wraps). */
export function hsv(h: number, s: number, v: number): RGB {
  let hh = h % 1.0;
  if (hh < 0) hh += 1.0;
  const ss = Math.max(0.0, Math.min(1.0, s));
  const vv = Math.max(0.0, Math.min(1.0, v));
  const [r, g, b] = hsvToRgbFloat(hh, ss, vv);
  return [clamp8(r * 255), clamp8(g * 255), clamp8(b * 255)];
}

/** Rotate a colour's hue by `delta` turns (0..1), keeping S and V. */
export function hueShift(c: RGB, delta: number): RGB {
  const [h, s, v] = rgbToHsvFloat(c[0] / 255.0, c[1] / 255.0, c[2] / 255.0);
  return hsv(h + delta, s, v);
}

/** A point on a smooth rainbow; `t` is a free-running time value. */
export function rainbow(t: number, sat = 0.85, val = 1.0): RGB {
  return hsv(t, sat, val);
}

/** Pack an RGB triple into a `0xRRGGBB` number, which is what Pixi wants. */
export function toHex(c: RGB): number {
  return (clamp8(c[0]) << 16) | (clamp8(c[1]) << 8) | clamp8(c[2]);
}

