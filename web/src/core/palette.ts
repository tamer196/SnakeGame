/** Every theme colour, packed as `0xRRGGBB` numbers for the renderer. */
export interface ThemeHex {
  readonly bgTop: number;
  readonly bgBottom: number;
  readonly grid: number;
  readonly accent: number;
  readonly accent2: number;
  readonly snakeHead: number;
  readonly snakeA: number;
  readonly snakeB: number;
  readonly food: number;
  readonly hazard: number;
  readonly text: number;
  readonly textDim: number;
}

/** The complete colour identity of one level. */
export interface Theme {
  readonly name: string;
  /** Key understood by the background renderer ("grid", "nebula", ...). */
  readonly bgStyle: string;
  /** Gradient sky colour, top of the arena. */
  readonly bgTop: RGB;
  /** Gradient colour at the bottom. */
  readonly bgBottom: RGB;
  /** Arena grid / lattice lines. */
  readonly grid: RGB;
  /** Primary neon: borders, highlights, UI focus. */
  readonly accent: RGB;
  /** Secondary neon: contrast pairings. */
  readonly accent2: RGB;
  readonly snakeHead: RGB;
  /** Body gradient start (head end). */
  readonly snakeA: RGB;
  /** Body gradient end (tail end). */
  readonly snakeB: RGB;
  readonly food: RGB;
  /** Walls, spikes, anything that hurts. */
  readonly hazard: RGB;
  readonly text: RGB;
  readonly textDim: RGB;
  /** The same palette as packed `0xRRGGBB` numbers, computed once at load. */
  readonly hex: ThemeHex;
}

/** Colour of a body segment: `t01` = 0 at the head, 1 at the tail tip. */
export function bodyAt(theme: Theme, t01: number): RGB {
  return lerpColor(theme.snakeA, theme.snakeB, t01);
}

// ---------------------------------------------------------------------------
// Loading the export
// ---------------------------------------------------------------------------

type RawRecord = Record<string, unknown>;

function readRgb(src: RawRecord, key: string): RGB {
  const v = src[key];
  if (Array.isArray(v) && v.length >= 3) {
    const r = v[0];
    const g = v[1];
    const b = v[2];
    if (typeof r === "number" && typeof g === "number" && typeof b === "number") {
      return [clamp8(r), clamp8(g), clamp8(b)];
    }
  }
  throw new Error(`themes.json: "${key}" is not an RGB triple`);
}

function readStr(src: RawRecord, key: string): string {
  const v = src[key];
  if (typeof v === "string") return v;
  throw new Error(`themes.json: "${key}" is not a string`);
}

function buildTheme(src: RawRecord): Theme {
  const bgTop = readRgb(src, "bg_top");
  const bgBottom = readRgb(src, "bg_bottom");
  const grid = readRgb(src, "grid");
  const accent = readRgb(src, "accent");
  const accent2 = readRgb(src, "accent2");
  const snakeHead = readRgb(src, "snake_head");
  const snakeA = readRgb(src, "snake_a");
  const snakeB = readRgb(src, "snake_b");
  const food = readRgb(src, "food");
  const hazard = readRgb(src, "hazard");
  const text = readRgb(src, "text");
  const textDim = readRgb(src, "text_dim");
  return {
    name: readStr(src, "name"),
    bgStyle: readStr(src, "bg_style"),
    bgTop,
    bgBottom,
    grid,
    accent,
    accent2,
    snakeHead,
    snakeA,
    snakeB,
    food,
    hazard,
    text,
    textDim,
    hex: {
      bgTop: toHex(bgTop),
      bgBottom: toHex(bgBottom),
      grid: toHex(grid),
      accent: toHex(accent),
      accent2: toHex(accent2),
      snakeHead: toHex(snakeHead),
      snakeA: toHex(snakeA),
      snakeB: toHex(snakeB),
      food: toHex(food),
      hazard: toHex(hazard),
      text: toHex(text),
      textDim: toHex(textDim),
    },
  };
}

const rawDoc = rawThemes as unknown as {
  themes: RawRecord[];
  ui: RawRecord;
};

/** The twelve level themes, ordered to match `LEVELS` in `core/level`. */
export const THEMES: readonly Theme[] = rawDoc.themes.map(buildTheme);

/** How many themes the export carried (12). */
export const THEME_COUNT: number = THEMES.length;

/** Theme for a zero-based level index; wraps for levels beyond the list. */
export function themeForLevel(index: number): Theme {
  if (THEMES.length === 0) throw new Error("no themes defined");
  const i = Number.isFinite(index) ? Math.trunc(index) : 0;
  const wrapped = ((i % THEMES.length) + THEMES.length) % THEMES.length;
  const theme = THEMES[wrapped];
  if (theme === undefined) throw new Error("no themes defined");
  return theme;
}

// ---------------------------------------------------------------------------
// Shared, theme-independent colours
// ---------------------------------------------------------------------------

function ui(key: string, fallback: RGB): RGB {
  const v = rawDoc.ui[key];
  if (Array.isArray(v) && v.length >= 3) return readRgb(rawDoc.ui, key);
  return fallback;
}

